type I18n = {
  lang: LangCode;
  setLang: (code: LangCode) => void;
  t: (text: string) => string;
  /** English language name ("Turkish") — sent to the agent so replies match the UI language. */
  langEnglishName: string;
};

const I18nContext = createContext<I18n>({
  lang: 'en',
  setLang: () => {},
  t: (text) => text,
  langEnglishName: 'English',
});

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<LangCode>('en');

  useEffect(() => {
    SecureStore.getItemAsync(LANG_KEY)
      .then((stored) => {
        if (stored && languages.some((entry) => entry.code === stored)) {
          setLangState(stored as LangCode);
        }
      })
      .catch(() => {});
  }, []);

  const setLang = (code: LangCode) => {
    setLangState(code);
    SecureStore.setItemAsync(LANG_KEY, code).catch(() => {});
  };

  const value = useMemo<I18n>(() => {
    const dict = lang === 'en' ? null : dictionaries[lang];
    return {
      lang,
      setLang,
      t: (text: string) => (dict && dict[text]) || text,
      langEnglishName: languages.find((entry) => entry.code === lang)?.english || 'English',
    };
  }, [lang]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}
